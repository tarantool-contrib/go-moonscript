package main

// The pinned corpus: the corpus check without the corpus sources, which are
// third-party code under assorted licenses and are not committed. Committed
// instead (testdata/corpus/):
//
//	manifest.tsv  where each distinct source file can be fetched from:
//	              "R TAB segment TAB owner/name TAB commit" lines, each
//	              followed by the "F TAB sha256 TAB blob id TAB path" lines
//	              of the files taken from that repository at that commit.
//	              Every distinct content is listed once, in a small set of
//	              repositories that covers them all (greedyCover: forks
//	              share most of their files).
//	expected.tsv  "id TAB ref TAB lint [TAB mutant ref]..." for every
//	              file of the manifest, id = sha256[:16]: digests of the
//	              reference outputs (see expected.go), the mutant ones in
//	              makeMutants order.
//
// Commands (on a corpus directory of its own, never a full corpus):
//
//	corpus export   write both files from a full local corpus (its
//	                manifest.tsv, files/, ref/, ref-lint/)
//	corpus fetch    fetch the manifest's files into <corpus>/files/, only
//	                the ones not there yet: per repository, one fetch of
//	                the blobs by id (a blob-less partial clone), or, if that
//	                fails, a shallow fetch of the pinned commit's trees and
//	                then of the blobs at the files' paths; contents are
//	                checked against their sha256. Repositories that are
//	                gone (deleted, made private, force-pushed and garbage
//	                collected) are reported and skipped; the fetch fails
//	                below -min-files of the files.
//	corpus prepare  regenerate the mutants of the files at hand and write
//	                <corpus>/manifest.tsv and <corpus>/expected.tsv, after
//	                which `corpus run` and `corpus -lint` check against the
//	                digests (-strict: exit status 1 on any difference)

