// pinRepo is a repository of the pinned manifest with the files taken
// from it.
type pinRepo struct {
	Segment, Repo, Commit string
	Files                 []pinFile
}

type pinFile struct {
	SHA  string // sha256 of the content; the corpus id is SHA[:16]
	Blob string // git blob id (optional)
	Path string
}

func (f pinFile) id() string { return f.SHA[:16] }

const pinHeader = `# go-moonscript real-world corpus: where to fetch each file from.
# Generated by scripts/gen-corpus-manifest.sh (corpus export); fetched by
# corpus fetch. See internal/tools/corpus/pinned.go and CONTRIBUTING.md.
# R <segment> <owner/name> <commit>: a GitHub repository at a pinned commit;
# F <sha256> <git blob id> <path>: a file of it.
`

const expectedHeader = `# go-moonscript real-world corpus: expected results, digests of the outputs
# of upstream moonc 0.8.0 (moonref:0.8.0) for each file of manifest.tsv.
# Generated by scripts/gen-corpus-manifest.sh (corpus export).
# <id> <ref> <lint> [<mutant ref>...]; formats: internal/tools/corpus/expected.go.
`

func readPinManifest(path string) ([]*pinRepo, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var repos []*pinRepo
	for i, line := range strings.Split(strings.TrimSuffix(string(data), "\n"), "\n") {
		if line == "" || line[0] == '#' {
			continue
		}
		c := strings.Split(line, "\t")
		switch {
		case c[0] == "R" && len(c) == 4:
			repos = append(repos, &pinRepo{Segment: c[1], Repo: c[2], Commit: c[3]})
		case c[0] == "F" && (len(c) == 3 || len(c) == 4) && len(repos) > 0 && len(c[1]) == 64:
			f := pinFile{SHA: c[1], Path: c[len(c)-1]}
			if len(c) == 4 {
				f.Blob = c[2]
			}
			repos[len(repos)-1].Files = append(repos[len(repos)-1].Files, f)
		default:
			return nil, fmt.Errorf("%s:%d: bad line %q", path, i+1, truncate(line, 80))
		}
	}
	return repos, nil
}

// readExpectedTSV reads a committed expected.tsv: id -> fields.
func readExpectedTSV(path string) (map[string][]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	m := map[string][]string{}
	for i, line := range strings.Split(strings.TrimSuffix(string(data), "\n"), "\n") {
		if line == "" || line[0] == '#' {
			continue
		}
		c := strings.Split(line, "\t")
		if len(c) < 3 || len(c[0]) != 16 {
			return nil, fmt.Errorf("%s:%d: bad line %q", path, i+1, truncate(line, 80))
		}
		m[c[0]] = c[1:]
	}
	return m, nil
}

// readAllOccurrences reads every line of a corpus manifest.tsv.
func readAllOccurrences(dir string) ([]Occurrence, error) {
	data, err := os.ReadFile(filepath.Join(dir, "manifest.tsv"))
	if err != nil {
		return nil, err
	}
	var occs []Occurrence
	for _, line := range strings.Split(strings.TrimSuffix(string(data), "\n"), "\n") {
		if line == manifestHeader || line == "" {
			continue
		}
		c := strings.SplitN(line, "\t", 8)
		if len(c) != 8 {
			return nil, fmt.Errorf("manifest.tsv: bad line %q", truncate(line, 80))
		}
		nb, _ := strconv.Atoi(c[2])
		nl, _ := strconv.Atoi(c[3])
		occs = append(occs, Occurrence{ID: c[0], SHA: c[1], Bytes: nb, Lines: nl, Segment: c[4], Repo: c[5], Commit: c[6], Path: c[7]})
	}
	return occs, nil
}

// mutantOrigin reports whether a file of segment seg gets mutants.
func mutantOrigin(seg string, lines int) bool { return seg == "moonscript" && lines <= 3000 }

// export writes manifest.tsv and expected.tsv into out from a full corpus.
func export(dir, out string) error {
	occs, err := readAllOccurrences(dir)
	if err != nil {
		return err
	}
	// distinct real files: segment of the first occurrence, as collect does
	first := map[string]*Occurrence{}
	var ids []string
	byRepo := map[string]map[string]string{} // segment\x00repo -> id -> path
	commits := map[string]string{}
	mutantsOf := map[string][]string{} // origin id -> mutant ids, from the corpus
	for i := range occs {
		o := &occs[i]
		if o.Segment == segmentMutants {
			mutantsOf[o.Commit] = append(mutantsOf[o.Commit], o.ID)
			continue
		}
		if first[o.ID] == nil {
			first[o.ID] = o
			ids = append(ids, o.ID)
		}
		if first[o.ID].Segment != o.Segment {
			continue
		}
		if strings.ContainsAny(o.Path, "\t\n") || strings.ContainsAny(o.Repo, "\t\n") {
			return fmt.Errorf("%s:%s: tab or newline in the name", o.Repo, o.Path)
		}
		key := o.Segment + "\x00" + o.Repo
		if byRepo[key] == nil {
			byRepo[key] = map[string]string{}
		}
		if p, ok := byRepo[key][o.ID]; !ok || o.Path < p {
			byRepo[key][o.ID] = o.Path
		}
		if c, ok := commits[key]; ok && c != o.Commit {
			return fmt.Errorf("%s: two commits", o.Repo)
		}
		commits[key] = o.Commit
	}

	cover := greedyCover(byRepo)
	var repos []*pinRepo
	covered := 0
	for _, key := range cover.order {
		seg, repo, _ := strings.Cut(key, "\x00")
		r := &pinRepo{Segment: seg, Repo: repo, Commit: commits[key]}
		for _, id := range cover.files[key] {
			o := first[id]
			data, err := os.ReadFile(filepath.Join(dir, "files", id+".moon"))
			if err != nil {
				return err
			}
			sum := sha256.Sum256(data)
			if hex.EncodeToString(sum[:]) != o.SHA {
				return fmt.Errorf("files/%s.moon: sha256 differs from manifest.tsv", id)
			}
			f := pinFile{SHA: o.SHA, Path: byRepo[key][id]}
			if *flagBlobIDs {
				f.Blob = gitBlobID(data)
			}
			r.Files = append(r.Files, f)
			covered++
		}
		repos = append(repos, r)
	}
	if covered != len(ids) {
		return fmt.Errorf("cover has %d of %d files", covered, len(ids))
	}
	sort.SliceStable(repos, func(i, j int) bool {
		si, sj := slices.Index(segmentOrder, repos[i].Segment), slices.Index(segmentOrder, repos[j].Segment)
		if si != sj {
			return si < sj
		}
		return repos[i].Repo < repos[j].Repo
	})

	var mb bytes.Buffer
	mb.WriteString(pinHeader)
	for _, r := range repos {
		fmt.Fprintf(&mb, "R\t%s\t%s\t%s\n", r.Segment, r.Repo, r.Commit)
		sort.Slice(r.Files, func(i, j int) bool { return r.Files[i].Path < r.Files[j].Path })
		for _, f := range r.Files {
			if f.Blob != "" {
				fmt.Fprintf(&mb, "F\t%s\t%s\t%s\n", f.SHA, f.Blob, f.Path)
			} else {
				fmt.Fprintf(&mb, "F\t%s\t%s\n", f.SHA, f.Path)
			}
		}
	}

	// expected results, with the mutants regenerated and checked against
	// the corpus' ones (collect skips the mutants already seen)
	var eb bytes.Buffer
	eb.WriteString(expectedHeader)
	seen := map[string]bool{}
	for _, id := range ids {
		seen[id] = true
	}
	drift, missing := 0, 0
	entry := func(e string) string {
		if e == "missing" {
			missing++
		}
		return e
	}
	// origin -> mutant entries; in manifest order, as collect
	origins := map[string][]string{}
	for _, id := range ids {
		o := first[id]
		if !mutantOrigin(o.Segment, o.Lines) {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, "files", id+".moon"))
		if err != nil {
			return err
		}
		var fresh, entries []string
		for _, m := range makeMutants(id, data, *flagMutants) {
			sum := sha256.Sum256(m.data)
			mid := hex.EncodeToString(sum[:8])
			if !seen[mid] {
				seen[mid] = true
				fresh = append(fresh, mid)
			}
			entries = append(entries, entry(refEntry(loadRef(dir, mid))))
		}
		if !slices.Equal(fresh, mutantsOf[id]) {
			drift++
			if drift <= 5 {
				fmt.Fprintf(os.Stderr, "mutants of %s: regenerated %v, corpus has %v\n", id, fresh, mutantsOf[id])
			}
		}
		origins[id] = entries
	}
	if drift > 0 {
		return fmt.Errorf("the mutants of %d files differ from the corpus' (re-run collect and ref)", drift)
	}
	for _, r := range repos {
		for _, f := range r.Files {
			id := f.id()
			lint := "-"
			if r.Segment == "moonscript" {
				lint = entry(lintEntry(loadLintRef(dir, id)))
			}
			fields := append([]string{id, entry(refEntry(loadRef(dir, id))), lint}, origins[id]...)
			eb.WriteString(strings.Join(fields, "\t") + "\n")
		}
	}
	if missing > 0 {
		return fmt.Errorf("%d reference results missing (run corpus ref and corpus ref -lint)", missing)
	}

	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	for name, b := range map[string][]byte{"manifest.tsv": mb.Bytes(), "expected.tsv": eb.Bytes()} {
		if err := os.WriteFile(filepath.Join(out, name), b, 0o644); err != nil {
			return err
		}
	}
	nm := 0
	for _, e := range origins {
		nm += len(e)
	}
	nrepos := map[string]bool{}
	for _, o := range occs {
		if o.Segment != segmentMutants {
			nrepos[o.Repo] = true
		}
	}
	fmt.Printf("%s: %d repositories (of %d with files), %d files, %s\n", filepath.Join(out, "manifest.tsv"),
		len(repos), len(nrepos), len(ids), human(mb.Len()))
	fmt.Printf("%s: %d files + %d mutants, %s\n", filepath.Join(out, "expected.tsv"), len(ids), nm, human(eb.Len()))
	return nil
}

// gitBlobID is the git object id of a blob with this content.
func gitBlobID(data []byte) string {
	h := sha1.New()
	h.Write([]byte("blob " + strconv.Itoa(len(data)) + "\x00"))
	h.Write(data)
	return hex.EncodeToString(h.Sum(nil))
}

type coverResult struct {
	order []string            // chosen repositories (segment\x00repo)
	files map[string][]string // repository -> the files taken from it
}

// greedyCover picks repositories until every file is covered, each time the
// one with the most files not yet covered (ties: by name), so that the
// fetch needs as few repositories as possible.
func greedyCover(byRepo map[string]map[string]string) coverResult {
	h := &coverHeap{}
	for key, files := range byRepo {
		*h = append(*h, coverItem{key, len(files)})
	}
	heap.Init(h)
	res := coverResult{files: map[string][]string{}}
	covered := map[string]bool{}
	for h.Len() > 0 {
		it := heap.Pop(h).(coverItem)
		var fresh []string
		for id := range byRepo[it.key] {
			if !covered[id] {
				fresh = append(fresh, id)
			}
		}
		if len(fresh) == 0 {
			continue
		}
		if len(fresh) < it.n { // stale count: re-queue
			heap.Push(h, coverItem{it.key, len(fresh)})
			continue
		}
		sort.Strings(fresh)
		for _, id := range fresh {
			covered[id] = true
		}
		res.order = append(res.order, it.key)
		res.files[it.key] = fresh
	}
	return res
}

type coverItem struct {
	key string
	n   int
}

type coverHeap []coverItem

func (h coverHeap) Len() int { return len(h) }
func (h coverHeap) Less(i, j int) bool {
	if h[i].n != h[j].n {
		return h[i].n > h[j].n
	}
	return h[i].key < h[j].key
}
func (h coverHeap) Swap(i, j int) { h[i], h[j] = h[j], h[i] }
func (h *coverHeap) Push(x any)   { *h = append(*h, x.(coverItem)) }
func (h *coverHeap) Pop() any {
	old := *h
	x := old[len(old)-1]
	*h = old[:len(old)-1]
	return x
}

// checkFetchedCorpus refuses a full corpus (reference outputs, no
// expected.tsv): fetch and prepare rewrite files/ and manifest.tsv.
func checkFetchedCorpus(dir string) error {
	_, errRef := os.Stat(filepath.Join(dir, "ref"))
	_, errExp := os.Stat(filepath.Join(dir, expectedFile))
	if errRef == nil && errExp != nil {
		return fmt.Errorf("%s has reference outputs (ref/): fetch and prepare need a directory of their own", dir)
	}
	return nil
}

// sourceOK reports whether files/<id>.moon holds the content with this sha256.
func sourceOK(dir string, f pinFile) bool {
	data, err := os.ReadFile(filepath.Join(dir, "files", f.id()+".moon"))
	if err != nil {
		return false
	}
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:]) == f.SHA
}

type fetchStats struct {
	mu                    sync.Mutex
	commitTime, blobTime  time.Duration
	failed                []string
	okRepos, files, bytes int
}

// fetch fetches the missing files of the manifest into <dir>/files.
func fetch(dir, manifest string) error {
	if err := checkFetchedCorpus(dir); err != nil {
		return err
	}
	repos, err := readPinManifest(manifest)
	if err != nil {
		return err
	}
	filesDir := filepath.Join(dir, "files")
	work := filepath.Join(dir, ".fetch")
	for _, d := range []string{filesDir, work} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			return err
		}
	}
	defer func() { _ = os.RemoveAll(work) }()

	// what is there already (a cached corpus), and stale files
	want := map[string]bool{}
	total := 0
	for _, r := range repos {
		for _, f := range r.Files {
			want[f.id()] = true
			total++
		}
	}
	old, _ := filepath.Glob(filepath.Join(filesDir, "*"))
	for _, p := range old {
		if !want[strings.TrimSuffix(filepath.Base(p), ".moon")] {
			if err := os.Remove(p); err != nil {
				return err
			}
		}
	}
	type job struct {
		r       *pinRepo
		missing []pinFile
	}
	var jobs []job
	have := 0
	for _, r := range repos {
		var missing []pinFile
		for _, f := range r.Files {
			if sourceOK(dir, f) {
				have++
			} else {
				missing = append(missing, f)
			}
		}
		if len(missing) > 0 {
			jobs = append(jobs, job{r, missing})
		}
	}
	fmt.Printf("fetch: %d repositories, %d files: %d present, fetching %d from %d repositories (%d at a time)\n",
		len(repos), total, have, total-have, len(jobs), *flagFetchJobs)

	start := time.Now()
	st := &fetchStats{}
	var done atomic.Int64
	ch := make(chan job)
	var wg sync.WaitGroup
	for range max(*flagFetchJobs, 1) {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for j := range ch {
				n, err := fetchRepo(dir, work, j.r, j.missing, st)
				st.mu.Lock()
				st.files += n
				if err != nil {
					st.failed = append(st.failed, fmt.Sprintf("%s@%.12s: %d of %d files missing: %v",
						j.r.Repo, j.r.Commit, len(j.missing)-n, len(j.missing), err))
				} else {
					st.okRepos++
				}
				st.mu.Unlock()
				if d := done.Add(1); d%100 == 0 {
					fmt.Fprintf(os.Stderr, "fetch: %d/%d repositories, %s\n", d, len(jobs), time.Since(start).Round(time.Second))
				}
			}
		}()
	}
	for _, j := range jobs {
		ch <- j
	}
	close(ch)
	wg.Wait()

	sort.Strings(st.failed)
	for _, f := range st.failed {
		fmt.Println("  skipped", f)
		if os.Getenv("GITHUB_ACTIONS") == "true" {
			fmt.Println("::warning title=corpus fetch::skipped " + f)
		}
	}
	present := have + st.files
	fmt.Printf("fetch: %d repositories fetched, %d failed; %d files (%s) in %s (git: commits %s, blobs %s)\n",
		st.okRepos, len(st.failed), st.files, human(st.bytes), time.Since(start).Round(time.Millisecond),
		st.commitTime.Round(time.Second), st.blobTime.Round(time.Second))
	fmt.Printf("fetch: %d of %d files present (%s)\n", present, total, pct(present, total))
	if total > 0 && float64(present) < *flagMinFiles*float64(total) {
		return fmt.Errorf("only %d of %d files present, below -min-files %.2f", present, total, *flagMinFiles)
	}
	return nil
}

// git runs git on the untrusted repository in dir: no hooks, no global or
// system configuration, no credential prompts.
func git(ctx context.Context, dir string, stdin io.Reader, stdout io.Writer, args ...string) error {
	base := []string{"-c", "core.hooksPath=/dev/null", "-c", "protocol.file.allow=never", "-c", "credential.helper=",
		"-c", "core.symlinks=false"}
	cmd := exec.CommandContext(ctx, "git", append(base, args...)...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GIT_TERMINAL_PROMPT=0", "GIT_CONFIG_NOSYSTEM=1", "GIT_CONFIG_GLOBAL=/dev/null",
		"GIT_ASKPASS=", "SSH_ASKPASS=", "GIT_LFS_SKIP_SMUDGE=1")
	if os.Getenv("GIT_SSH_COMMAND") == "" {
		cmd.Env = append(cmd.Env, "GIT_SSH_COMMAND=ssh -o BatchMode=yes")
	}
	cmd.Stdin, cmd.Stdout = stdin, stdout
	var stderr capBuf
	stderr.max = 4 << 10
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		msg := firstLine(strings.TrimSpace(stderr.String())) // e.g. "ERROR: Repository not found."
		if ctx.Err() != nil {
			msg = "timed out"
		}
		return fmt.Errorf("git %s: %s", args[0], orStr(msg, err.Error()))
	}
	return nil
}

// fetchRepo fetches the files of one repository; it returns how many it
// wrote.
func fetchRepo(dir, work string, r *pinRepo, files []pinFile, st *fetchStats) (int, error) {
	ctx, cancel := context.WithTimeout(context.Background(), *flagFetchTO)
	defer cancel()
	tmp, err := os.MkdirTemp(work, "repo-")
	if err != nil {
		return 0, err
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	if err := git(ctx, tmp, nil, nil, "init", "-q", "--bare", "."); err != nil {
		return 0, err
	}
	url := fmt.Sprintf(*flagGitURL, r.Repo)
	// a partial clone: blobs are fetched on demand
	config := fmt.Sprintf("[core]\n\trepositoryformatversion = 1\n\tbare = true\n[extensions]\n\tpartialClone = origin\n"+
		"[remote \"origin\"]\n\turl = %s\n\tpromisor = true\n\tpartialclonefilter = blob:none\n", url)
	if err := os.WriteFile(filepath.Join(tmp, "config"), []byte(config), 0o644); err != nil {
		return 0, err
	}

	// the blobs, by the ids of the manifest: a single fetch; else (no ids,
	// or the server refuses them) by those of the pinned commit's tree
	var blobs map[string]pinFile // blob id -> file
	var need []string
	fetchBlobs := func() error {
		if len(need) == 0 {
			return nil
		}
		t := time.Now()
		defer func() {
			st.mu.Lock()
			st.blobTime += time.Since(t)
			st.mu.Unlock()
		}()
		return git(ctx, tmp, strings.NewReader(strings.Join(need, "\n")+"\n"), nil,
			"-c", "fetch.negotiationAlgorithm=noop", "fetch", "-q", "--no-tags", "--no-write-fetch-head",
			"--recurse-submodules=no", "--filter=blob:none", "--stdin", "origin")
	}
	err = errors.New("no blob ids")
	if !slices.ContainsFunc(files, func(f pinFile) bool { return f.Blob == "" }) {
		blobs, need = map[string]pinFile{}, nil
		for _, f := range files {
			blobs[f.Blob] = f
			need = append(need, f.Blob)
		}
		err = fetchBlobs()
	}
	if err != nil {
		if blobs, need, err = treeBlobs(ctx, tmp, r, files, st); err != nil {
			return 0, err
		}
		if err := fetchBlobs(); err != nil {
			return 0, err
		}
	}

	// contents: git cat-file --batch, checked against the sha256
	var out bytes.Buffer
	if err := git(ctx, tmp, strings.NewReader(strings.Join(need, "\n")+"\n"), &out, "cat-file", "--batch"); err != nil {
		return 0, err
	}
	n, nbytes := 0, 0
	rd := bufio.NewReader(&out)
	var bad []string
	for range need {
		hdr, err := rd.ReadString('\n')
		if err != nil {
			return n, errors.New("short git cat-file output")
		}
		f := strings.Fields(hdr)
		if len(f) != 3 || f[1] != "blob" {
			continue // "<id> missing"
		}
		size, _ := strconv.Atoi(f[2])
		data := make([]byte, size+1)
		if _, err := io.ReadFull(rd, data); err != nil {
			return n, errors.New("short git cat-file output")
		}
		data = data[:size]
		pf := blobs[f[0]]
		sum := sha256.Sum256(data)
		if hex.EncodeToString(sum[:]) != pf.SHA {
			bad = append(bad, pf.Path)
			continue
		}
		p := filepath.Join(dir, "files", pf.id()+".moon")
		if err := os.WriteFile(p+".tmp", data, 0o644); err != nil {
			return n, err
		}
		if err := os.Rename(p+".tmp", p); err != nil {
			return n, err
		}
		n++
		nbytes += size
	}
	st.mu.Lock()
	st.bytes += nbytes
	st.mu.Unlock()
	switch {
	case len(bad) > 0:
		return n, fmt.Errorf("sha256 mismatch: %s", strings.Join(bad, ", "))
	case n < len(files):
		return n, errors.New("files not found at the commit")
	}
	return n, nil
}

// treeBlobs fetches the tree of the pinned commit and returns the blob ids
// of the files.
func treeBlobs(ctx context.Context, tmp string, r *pinRepo, files []pinFile, st *fetchStats) (map[string]pinFile, []string, error) {
	t := time.Now()
	defer func() {
		st.mu.Lock()
		st.commitTime += time.Since(t)
		st.mu.Unlock()
	}()
	if err := git(ctx, tmp, nil, nil, "fetch", "-q", "--depth=1", "--filter=blob:none", "--no-tags",
		"--no-write-fetch-head", "--recurse-submodules=no", "origin", r.Commit); err != nil {
		return nil, nil, err
	}
	var tree bytes.Buffer
	if err := git(ctx, tmp, nil, &tree, "ls-tree", "-r", "-z", "--full-tree", r.Commit); err != nil {
		return nil, nil, err
	}
	paths := map[string]string{}
	for _, ent := range strings.Split(tree.String(), "\x00") {
		meta, path, ok := strings.Cut(ent, "\t")
		if f := strings.Fields(meta); ok && len(f) == 3 && f[1] == "blob" {
			paths[path] = f[2]
		}
	}
	blobs := map[string]pinFile{}
	var need []string
	for _, f := range files {
		if b, ok := paths[f.Path]; ok {
			blobs[b] = f
			need = append(need, b)
		}
	}
	return blobs, need, nil
}

// prepare makes a fetched corpus ready for run and -lint: mutants,
// manifest.tsv and expected.tsv.
func prepare(dir, manifest, expectedPath string) error {
	if err := checkFetchedCorpus(dir); err != nil {
		return err
	}
	repos, err := readPinManifest(manifest)
	if err != nil {
		return err
	}
	exp, err := readExpectedTSV(expectedPath)
	if err != nil {
		return err
	}
	var occs []Occurrence
	entries := map[string]expectedEntry{}
	var origins []int // indexes of the mutant origins in occs
	total := 0
	for _, r := range repos {
		for _, f := range r.Files {
			total++
			id := f.id()
			data, err := os.ReadFile(filepath.Join(dir, "files", id+".moon"))
			if err != nil {
				continue // not fetched
			}
			sum := sha256.Sum256(data)
			if hex.EncodeToString(sum[:]) != f.SHA {
				return fmt.Errorf("files/%s.moon: sha256 mismatch (run corpus fetch)", id)
			}
			e := exp[id]
			if e == nil {
				return fmt.Errorf("%s: no expected results for %s (%s:%s)", expectedPath, id, r.Repo, f.Path)
			}
			entries[id] = expectedEntry{e[0], e[1]}
			o := Occurrence{ID: id, SHA: f.SHA, Bytes: len(data), Lines: countLines(data), Segment: r.Segment,
				Repo: r.Repo, Commit: r.Commit, Path: f.Path}
			if mutantOrigin(o.Segment, o.Lines) {
				origins = append(origins, len(occs))
			}
			occs = append(occs, o)
		}
	}
	nreal := len(occs)
	drift := 0
	for _, i := range origins {
		o := occs[i]
		data, err := os.ReadFile(filepath.Join(dir, "files", o.ID+".moon"))
		if err != nil {
			return err
		}
		muts := makeMutants(o.ID, data, *flagMutants)
		want := exp[o.ID][2:]
		if len(muts) != len(want) {
			drift++
			continue
		}
		for k, m := range muts {
			sum := sha256.Sum256(m.data)
			sha := hex.EncodeToString(sum[:])
			id := sha[:16]
			if _, dup := entries[id]; dup {
				continue
			}
			entries[id] = expectedEntry{want[k], "-"}
			if err := os.WriteFile(filepath.Join(dir, "files", id+".moon"), m.data, 0o644); err != nil {
				return err
			}
			occs = append(occs, Occurrence{ID: id, SHA: sha, Bytes: len(m.data), Lines: countLines(m.data),
				Segment: segmentMutants, Repo: mutantPrefix + m.kind, Commit: o.ID, Path: o.Repo + "/" + o.Path + m.detail})
		}
	}
	if drift > 0 {
		return fmt.Errorf("%d files have a different number of mutants than expected.tsv: "+
			"the mutant generator changed (regenerate the corpus references)", drift)
	}

	var mb, eb bytes.Buffer
	mb.WriteString(manifestHeader + "\n")
	for _, o := range occs {
		fmt.Fprintf(&mb, "%s\t%s\t%d\t%d\t%s\t%s\t%s\t%s\n", o.ID, o.SHA, o.Bytes, o.Lines, o.Segment, o.Repo, o.Commit, o.Path)
		e := entries[o.ID]
		fmt.Fprintf(&eb, "%s\t%s\t%s\n", o.ID, e.ref, e.lint)
	}
	if err := os.WriteFile(filepath.Join(dir, "manifest.tsv"), mb.Bytes(), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, expectedFile), eb.Bytes(), 0o644); err != nil {
		return err
	}
	fmt.Printf("prepare: %d of %d files of the manifest (%s), %d mutants\n", nreal, total, pct(nreal, total), len(occs)-nreal)
	return nil
}
