// Command gendispatch extracts the FIRST-byte dispatch tables that pgen
// emitted into moonscript/parse/slow.lua and writes them as Go source
// (moonscript/parse/dispatch_gen.go), so DAlt can skip and record exactly like pgen.
//
//	go run ./internal/tools/gendispatch -slow path/to/slow.lua -o moonscript/parse/dispatch_gen.go
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"strconv"
)

type mask struct {
	alts, s uint64
}

type table struct {
	id    int
	masks map[string]mask
	def   string
	eof   string
	bytes map[int]string
}

var (
	reChoice = regexp.MustCompile(`^do -- dispatch tables for choice (\d+)$`)
	reMask   = regexp.MustCompile(`^\s*local (dmask\d+) = \{(.*) s = \{(.*)\}, full = (true|false) \}$`)
	reIdx    = regexp.MustCompile(`\[(\d+)\] = true`)
	reDef    = regexp.MustCompile(`^\s*for b = 0, 255 do bytes\[b\] = (dmask\d+) end$`)
	reByte   = regexp.MustCompile(`^\s*bytes\[(\d+)\] = (dmask\d+)$`)
	reDisp   = regexp.MustCompile(`^\s*disp\[(\d+)\] = \{ bytes = bytes, eof = (dmask\d+) \}$`)
)

func bits(s string) uint64 {
	var b uint64
	for _, m := range reIdx.FindAllStringSubmatch(s, -1) {
		k, _ := strconv.Atoi(m[1])
		if k < 1 || k > 64 {
			log.Fatalf("alternative index %d out of range", k)
		}
		b |= 1 << (k - 1)
	}
	return b
}

func main() {
	slow := flag.String("slow", "", "path to moonscript/parse/slow.lua")
	out := flag.String("o", "moonscript/parse/dispatch_gen.go", "output file")
	flag.Parse()

	f, err := os.Open(*slow)
	if err != nil {
		log.Fatal(err)
	}
	defer func() { _ = f.Close() }()

	var tables []*table
	var cur *table
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if m := reChoice.FindStringSubmatch(line); m != nil {
			id, _ := strconv.Atoi(m[1])
			cur = &table{id: id, masks: map[string]mask{}, bytes: map[int]string{}}
			continue
		}
		if cur == nil {
			continue
		}
		if m := reMask.FindStringSubmatch(line); m != nil {
			cur.masks[m[1]] = mask{alts: bits(m[2]), s: bits(m[3])}
		} else if m := reDef.FindStringSubmatch(line); m != nil {
			cur.def = m[1]
		} else if m := reByte.FindStringSubmatch(line); m != nil {
			b, _ := strconv.Atoi(m[1])
			cur.bytes[b] = m[2]
		} else if m := reDisp.FindStringSubmatch(line); m != nil {
			id, _ := strconv.Atoi(m[1])
			if id != cur.id {
				log.Fatalf("choice %d stored as disp[%d]", cur.id, id)
			}
			cur.eof = m[2]
			tables = append(tables, cur)
			cur = nil
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if len(tables) == 0 {
		log.Fatal("no dispatch tables found")
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/tools/gendispatch from moonscript/parse/slow.lua; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package parse\n\n")
	fmt.Fprintf(&b, "// dispatchTables[id-1] is pgen's disp[id]: for each next input byte (and\n")
	fmt.Fprintf(&b, "// end of input) the bitmask of alternatives to try (bit k-1 = alternative\n")
	fmt.Fprintf(&b, "// k) and the alternatives preceded by a furthest-failure record.\n")
	fmt.Fprintf(&b, "var dispatchTables = [...]dispatchTable{\n")
	for i, t := range tables {
		if t.id != i+1 {
			log.Fatalf("dispatch tables out of order: %d at %d", t.id, i+1)
		}
		get := func(name string) mask {
			m, ok := t.masks[name]
			if !ok {
				log.Fatalf("choice %d: unknown mask %s", t.id, name)
			}
			return m
		}
		fmt.Fprintf(&b, "\t{ // choice %d\n", t.id)
		eof := get(t.eof)
		fmt.Fprintf(&b, "\t\teof: dispatchMask{alts: %#x, s: %#x},\n", eof.alts, eof.s)
		fmt.Fprintf(&b, "\t\tbytes: [256]dispatchMask{\n")
		def := get(t.def)
		for c := 0; c < 256; c++ {
			m := def
			if name, ok := t.bytes[c]; ok {
				m = get(name)
			}
			fmt.Fprintf(&b, "\t\t\t%d: {alts: %#x, s: %#x},\n", c, m.alts, m.s)
		}
		fmt.Fprintf(&b, "\t\t},\n\t},\n")
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
